import gradio as gr

# =========================================================
# 【表示処理（バックエンド）】
# 他メンバー（山際・安斎・椎名）から受け取ったデータを
# テキストとマップ（HTML）の表示用データに整形する関数
# =========================================================
def format_display_output(keyword, genre_filter, budget_min, budget_max, smoking):
    # ---------------------------------------------------------
    # ※本番ではここに他メンバーの判定結果（上位店舗データ）が入ります。
    # 画面の表示確認用に固定のダミーデータを1件用意しています。
    # ---------------------------------------------------------
    recommended_list = [
        {
            "店名": "サンプル店舗",
            "ジャンル": genre_filter if genre_filter != "すべて" else "居酒屋",
            "目安予算": f"{budget_min}～{budget_max}円",
            "Google評価": "★4.5",
            "喫煙環境": smoking if smoking != "こだわらない" else "全面禁煙",
            "住所": "千葉県習志野市大久保1-1-1",
            "緯度": 35.6888,
            "経度": 140.0514
        }
    ]

    # 店舗が見つからない場合の表示（他メンバーのロジックで空の場合）
    if not recommended_list:
        empty_map = "<div style='padding:10px; border:1px solid #ccc; text-align:center;'>条件に合うお店が見つかりませんでした。</div>"
        return "条件に合うお店が見つかりませんでした。", empty_map

    # 1. テキスト出力結果の組み立て
    result_text = f"【検索結果】 キーワード: '{keyword or '指定なし'}' / ジャンル: {genre_filter} / 予算: {budget_min}円〜{budget_max}円\n\n"

    for shop in recommended_list:
        result_text += f"■ {shop['店名']}\n"
        result_text += f"・ジャンル: {shop['ジャンル']}\n"
        result_text += f"・目安予算: {shop['目安予算']}\n"
        result_text += f"・Google評価: {shop['Google評価']}\n"
        result_text += f"・喫煙環境: {shop['喫煙環境']}\n"
        result_text += f"・住所: {shop['住所']}\n\n"

    # 2. Google Maps埋め込み用HTMLの組み立て
    center_lat = recommended_list[0]["緯度"]
    center_lng = recommended_list[0]["経度"]

    iframe_content = f"""<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <style>
    html, body {{ height: 100%; margin: 0; padding: 0; }}
    #map {{ height: 100%; width: 100%; }}
  </style>
</head>
<body>
  <div id="map"></div>
  <script>
    function initMap() {{
      const map = new google.maps.Map(document.getElementById("map"), {{
        zoom: 15,
        center: {{ lat: {center_lat}, lng: {center_lng} }}
      }});
      new google.maps.Marker({{
        position: {{ lat: {center_lat}, lng: {center_lng} }},
        map: map,
        title: "{recommended_list[0]['店名']}"
      }});
    }}
  </script>
  <script async src="https://maps.googleapis.com/maps/api/js?key=AIzaSyBS_M1Bg9kZnybyF33PItQfG2CvfP-X9y0&callback=initMap"></script>
</body>
</html>"""

    import html
    escaped_srcdoc = html.escape(iframe_content, quote=True)
    map_html = f"""
    <div style="margin-top: 10px;">
      <h3 style="margin-bottom: 5px; font-size: 16px;">📍 おすすめ店舗の場所マップ</h3>
      <iframe srcdoc="{escaped_srcdoc}" style="width: 100%; height: 280px; border: 1px solid #ccc; border-radius: 8px;"></iframe>
    </div>
    """

    return result_text, map_html


# =========================================================
# 【表示UI（画面レイアウト構築）】
# Gradio画面のコンポーネント配置
# =========================================================
with gr.Blocks(title="習志野・大久保周辺 おすすめナビ") as demo:
    gr.Markdown("## 習志野・大久保周辺 パーソナライズおすすめナビ")

    with gr.Row():
        # --- 左カラム：入力領域 ---
        with gr.Column():
            keyword_in = gr.Textbox(
                label="キーワード検索（料理名、こだわり、雰囲気など）",
                placeholder="例: から揚げ、オムライス、個室、生ラム"
            )
            genre_in = gr.Dropdown(
                ["すべて", "居酒屋", "カフェ・スイーツ", "ラーメン", "焼肉・ホルモン", "和食", "ダイニングバー・バル"],
                label="ジャンル",
                value="すべて"
            )
            b_min_in = gr.Slider(minimum=0, maximum=10000, value=0, step=500, label="予算の下限 (円)")
            b_max_in = gr.Slider(minimum=0, maximum=10000, value=5000, step=500, label="予算の上限 (円)")
            smoking_in = gr.Dropdown(["こだわらない", "全面禁煙のみ"], label="喫煙環境", value="こだわらない")

            submit_btn = gr.Button("おすすめ店舗を検索", variant="primary")

        # --- 右カラム：出力表示領域 ---
        with gr.Column():
            result_out = gr.Textbox(label="おすすめ店舗一覧", lines=10)
            map_out = gr.HTML(label="マップ表示")

    # ボタン押下時の処理イベント結合
    submit_btn.click(
        fn=format_display_output,
        inputs=[keyword_in, genre_in, b_min_in, b_max_in, smoking_in],
        outputs=[result_out, map_out]
    )

demo.launch(share=True)